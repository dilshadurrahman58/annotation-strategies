"""Build web images for the nine figures the paper shows. Run from the repo root:  python3 tools/make_images.py

- images/web/<id>-card.webp  cards and strategy plates, at most 960 px wide
- images/web/<id>.webp       detail view and full size, at most 2000 px wide
- data/sizes.js              natural pixel sizes, so images reserve their space
The source PNGs in professional-vis-examples/ stay as they are and remain the fallback.
"""
import json
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
IDS = ["40_WSJ_BAR", "8_WP_BAR", "64_ECO_SCATTER", "4_WP_LINE", "25_NYT_LINE",
       "19_NYT_SCATTER", "11_WP_LINE", "24_NYT_BAR", "67_ECO_LINE"]

def fit(im, max_w):
    if im.width <= max_w:
        return im
    return im.resize((max_w, round(im.height * max_w / im.width)), Image.LANCZOS)

out = ROOT / "images/web"
out.mkdir(parents=True, exist_ok=True)
sizes = {}
for i in IDS:
    im = Image.open(ROOT / f"professional-vis-examples/{i}.png").convert("RGBA")
    bg = Image.new("RGBA", im.size, (255, 255, 255, 255))
    im = Image.alpha_composite(bg, im).convert("RGB")
    fit(im, 960).save(out / f"{i}-card.webp", "WEBP", quality=86, method=6)
    fit(im, 2000).save(out / f"{i}.webp", "WEBP", quality=90, method=6)
    sizes[i] = [im.width, im.height]

(ROOT / "data/sizes.js").write_text(
    "// generated by tools/make_images.py: natural pixel sizes, so images reserve their space\n"
    f"window.FIGURE_SIZES = {json.dumps(sizes, separators=(',', ':'))};\n")
print(sizes)
